#!/usr/bin/env node
// make-launcher-icon.mjs — builds the KAST launcher icon from its one vector source (bugs/05).
//   node tools/make-launcher-icon.mjs            # from the repository root; needs ImageMagick 7 (`magick`) with librsvg
//
// Source: assets/logo/kast-icon.svg — #plate (the dark rounded square) and #glyph (frame, screen, notch, pixel squares).
// Writes:
//   res/drawable-v24/ic_launcher_foreground.xml   adaptive icon foreground (Android 8+), vector; the gradient needs API 24, hence -v24
//   res/drawable-v24/ic_launcher_monochrome.xml   themed-icon layer (Android 13+): the glyph in white, without the notch
//   res/values/ic_launcher_background.xml     the background colour = the plate colour
//   res/mipmap-*/ic_launcher.webp             the whole icon (plate + glyph) for Android 7 and older, lossless WebP
// and removes the Moonlight rasters it replaces (mipmap-*/ic_launcher.png, mipmap-*/ic_launcher_foreground.png).
// Placement: the plate centre goes to the centre of the 108-unit canvas, scaled so the farthest glyph point stays
// inside the 66-unit safe circle of adaptive icons (the glyph then spans ~53 of the 72 visible units).
// [TESTED: 2026-09-26 · run from the repo root; the built APK shows the KAST icon in the Titan launcher (bugs/05)]
import { readFileSync, writeFileSync, existsSync, unlinkSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const SVG = 'assets/logo/kast-icon.svg';
const RES = 'app/src/main/res';
const src = readFileSync(SVG, 'utf8');

const attrsOf = (id) => {
  const m = src.match(new RegExp(`<(path|rect)\\s+id="${id}"([^>]*?)/>`, 's'));
  if (!m) throw new Error(`no element #${id} in ${SVG}`);
  const a = { tag: m[1] };
  for (const [, k, v] of m[2].matchAll(/([\w-]+)="([^"]*)"/g)) a[k] = v;
  return a;
};
// A rounded rect as path data (arcs are legal in VectorDrawable pathData).
const rectPath = ({ x, y, width, height, rx }) => {
  const [X, Y, W, H, R] = [x, y, width, height, rx || 0].map(Number);
  return `M ${X + R} ${Y} H ${X + W - R} A ${R} ${R} 0 0 1 ${X + W} ${Y + R} V ${Y + H - R} A ${R} ${R} 0 0 1 ${X + W - R} ${Y + H}` +
    ` H ${X + R} A ${R} ${R} 0 0 1 ${X} ${Y + H - R} V ${Y + R} A ${R} ${R} 0 0 1 ${X + R} ${Y} Z`;
};
const pathData = (a) => (a.tag === 'rect' ? rectPath(a) : a.d.replace(/\s+/g, ' ').trim());

const plate = attrsOf('plate');
const [px, py, pw, ph] = ['x', 'y', 'width', 'height'].map((k) => Number(plate[k]));
const cx = px + pw / 2, cy = py + ph / 2;
const GLYPH = ['frame', 'screen', 'notch', 'px1', 'px2', 'px3', 'px4', 'px5'];
const parts = GLYPH.map((id) => ({ id, ...attrsOf(id) }));

// Farthest glyph point from the plate centre, sampled on the path data's numbers (coordinates come in x y pairs).
let far = 0;
for (const p of parts) {
  const nums = pathData(p).replace(/[A-Za-z]/g, ' ').trim().split(/\s+/).map(Number);
  if (p.tag === 'rect') {
    const [X, Y, W, H] = ['x', 'y', 'width', 'height'].map((k) => Number(p[k]));
    for (const [qx, qy] of [[X, Y], [X + W, Y], [X, Y + H], [X + W, Y + H]]) far = Math.max(far, Math.hypot(qx - cx, qy - cy));
  } else {
    for (let i = 0; i + 1 < nums.length; i += 2) far = Math.max(far, Math.hypot(nums[i] - cx, nums[i + 1] - cy));
  }
}
const SAFE_R = 33;                       // half of the 66-unit safe zone of a 108-unit adaptive icon
const s = +(SAFE_R / far).toFixed(5);
const tx = +(54 - cx * s).toFixed(3), ty = +(54 - cy * s).toFixed(3);

const grad = src.match(/<linearGradient id="screenFill"([^>]*)>([\s\S]*?)<\/linearGradient>/);
const g = {}; for (const [, k, v] of grad[1].matchAll(/([\w-]+)="([^"]*)"/g)) g[k] = v;
const stops = [...grad[2].matchAll(/offset="([^"]+)" stop-color="([^"]+)"/g)].map(([, o, c]) => ({ o, c }));

const header = (w) => `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/make-launcher-icon.mjs from assets/logo/kast-icon.svg — edit the SVG and rerun the script (bugs/05). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"${w ? '\n    xmlns:aapt="http://schemas.android.com/aapt"' : ''}
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="${s}" android:scaleY="${s}" android:translateX="${tx}" android:translateY="${ty}">
`;
const argb = (hex) => '#FF' + hex.replace('#', '').toUpperCase();

let fg = header(true);
for (const p of parts) {
  if (p.fill && p.fill.startsWith('url(')) {
    fg += `        <path android:pathData="${pathData(p)}">
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="${g.x1}" android:startY="${g.y1}" android:endX="${g.x2}" android:endY="${g.y2}">
${stops.map((t) => `                    <item android:offset="${t.o}" android:color="${argb(t.c)}"/>`).join('\n')}
                </gradient>
            </aapt:attr>
        </path>
`;
  } else {
    fg += `        <path android:fillColor="${argb(p.fill)}" android:pathData="${pathData(p)}"/>\n`;
  }
}
fg += '    </group>\n</vector>\n';

let mono = header(false);
for (const p of parts.filter((q) => q.id !== 'notch')) mono += `        <path android:fillColor="#FFFFFFFF" android:pathData="${pathData(p)}"/>\n`;
mono += '    </group>\n</vector>\n';

writeFileSync(`${RES}/drawable-v24/ic_launcher_foreground.xml`, fg);
writeFileSync(`${RES}/drawable-v24/ic_launcher_monochrome.xml`, mono);
writeFileSync(`${RES}/values/ic_launcher_background.xml`, `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/make-launcher-icon.mjs: the plate colour of assets/logo/kast-icon.svg (bugs/05). -->
<resources>
  <color name="ic_launcher_background">${plate.fill.toUpperCase()}</color>
</resources>
`);

// Android 7 and older: the whole icon, 48 dp.
const SIZES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [d, px48] of Object.entries(SIZES)) {
  const dir = `${RES}/mipmap-${d}`;
  execFileSync('magick', ['-background', 'none', '-density', '384', SVG, '-resize', `${px48}x${px48}`,
    '-define', 'webp:lossless=true', `${dir}/ic_launcher.webp`]);
  for (const old of ['ic_launcher.png', 'ic_launcher_foreground.png']) if (existsSync(`${dir}/${old}`)) unlinkSync(`${dir}/${old}`);
}
console.log(`scale ${s} · translate ${tx},${ty} · farthest glyph point ${far.toFixed(1)} px → ${(far * s).toFixed(2)} of 33 units`);
console.log(`background ${plate.fill} · the bound is taken on control points, the real curve lies slightly inside`);
